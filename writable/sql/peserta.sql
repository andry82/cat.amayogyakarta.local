SELECT
  `r`.`id`                   AS `id`,
  `r`.`no_registrasi`        AS `no_registrasi`,
  `r`.`nama_lengkap`         AS `nama_lengkap`,
  `r`.`kode_test`            AS `kode_test`,
  `r`.`desa_id`              AS `desa_id`,
  `r`.`tanggal_registrasi`   AS `tanggal_registrasi`,
  `r`.`user_id`              AS `user_id`,
  `r`.`mulai_tes_tertulis`   AS `mulai_tes_tertulis`,
  `r`.`selesai_tes_tertulis` AS `selesai_tes_tertulis`,
  `r`.`sisa_waktu_tertulis`  AS `sisa_waktu_tertulis`,
  `r`.`skor_tertulis`        AS `skor_tertulis`,
  `r`.`mulai_tes_praktik`    AS `mulai_tes_praktik`,
  `r`.`selesai_tes_praktik`  AS `selesai_tes_praktik`,
  `r`.`sisa_waktu_praktik`   AS `sisa_waktu_praktik`,
  `r`.`skor_praktik`         AS `skor_praktik`,
  `r`.`skor_word`            AS `skor_word`,
  `r`.`skor_excel`           AS `skor_excel`,
  `r`.`skor_ppt`             AS `skor_ppt`,
  `r`.`skor_email`           AS `skor_email`,
  `r`.`skor_wawancara`       AS `skor_wawancara`,
  `r`.`last_page`            AS `last_page`,
  `r`.`word1`                AS `word1`,
  `r`.`word2`                AS `word2`,
  `r`.`word3`                AS `word3`,
  `r`.`excel1`               AS `excel1`,
  `r`.`excel2`               AS `excel2`,
  `r`.`excel3`               AS `excel3`,
  `r`.`ppt1`                 AS `ppt1`,
  `r`.`ppt2`                 AS `ppt2`,
  `r`.`ppt3`                 AS `ppt3`,
  `r`.`email1`               AS `email1`,
  `r`.`email2`               AS `email2`,
  `r`.`email3`               AS `email3`,
  `r`.`interview1`           AS `interview1`,
  `r`.`interview2`           AS `interview2`,
  `r`.`interview3`           AS `interview3`,
  `r`.`interview11`          AS `interview11`,
  `r`.`interview12`          AS `interview12`,
  `r`.`interview13`          AS `interview13`,
  `r`.`interview14`          AS `interview14`,
  `r`.`interview15`          AS `interview15`,
  `r`.`interview21`          AS `interview21`,
  `r`.`interview22`          AS `interview22`,
  `r`.`interview23`          AS `interview23`,
  `r`.`interview24`          AS `interview24`,
  `r`.`interview25`          AS `interview25`,
  `r`.`interview31`          AS `interview31`,
  `r`.`interview32`          AS `interview32`,
  `r`.`interview33`          AS `interview33`,
  `r`.`interview34`          AS `interview34`,
  `r`.`interview35`          AS `interview35`,
  `r`.`pewawancara_id`       AS `pewawancara_id`,
  `t`.`nama_test`            AS `nama_test`,
  `t`.`tanggal_test`         AS `tanggal_test`,
  `t`.`prosentase_tertulis`  AS `prosentase_tertulis`,
  `t`.`prosentase_praktik`   AS `prosentase_praktik`,
  `t`.`prosentase_wawancara` AS `prosentase_wawancara`,
  `d`.`nama_desa`            AS `nama_desa`,
  `u`.`fullname`             AS `fullname`
FROM (((`registrasi` `r`
     JOIN `tests` `t`
       ON ((`r`.`kode_test` = `t`.`kode_test`)))
    JOIN `desa` `d`
      ON ((`r`.`desa_id` = `d`.`id`)))
   LEFT JOIN `users` `u`
     ON ((`r`.`pewawancara_id` = `u`.`id`)))
ORDER BY `r`.`no_registrasi`;